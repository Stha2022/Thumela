CREATE TABLE payment_quotes (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 quote_token CHAR(48) NOT NULL UNIQUE,
 user_id BIGINT UNSIGNED NOT NULL,
 recipient_id INT NOT NULL,
 amount DECIMAL(18,2) NOT NULL,
 fee DECIMAL(18,2) NOT NULL,
 total DECIMAL(18,2) NOT NULL,
 expires_at DATETIME NOT NULL,
 used TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_quote_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 CONSTRAINT fk_quote_recipient FOREIGN KEY (recipient_id) REFERENCES recipients(id)
) ENGINE=InnoDB;

CREATE TABLE transactions (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 reference VARCHAR(30) NOT NULL UNIQUE,
 recipient_id INT NULL,
 recipient_name VARCHAR(100) NOT NULL,
 amount DECIMAL(18,2) NOT NULL,
 fee DECIMAL(18,2) NOT NULL DEFAULT 0,
 status VARCHAR(40) NOT NULL,
 network VARCHAR(40) NOT NULL DEFAULT 'Demo',
 tx_hash VARCHAR(100) NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_tx_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 CONSTRAINT fk_tx_recipient FOREIGN KEY (recipient_id) REFERENCES recipients(id)
) ENGINE=InnoDB;

CREATE TABLE savings_goals (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(100) NOT NULL,
 target_amount DECIMAL(18,2) NOT NULL,
 saved_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
 target_date DATE NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_goal_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE payment_requests (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 request_code VARCHAR(24) NOT NULL UNIQUE,
 amount DECIMAL(18,2) NULL,
 note VARCHAR(160) NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 expires_at DATETIME NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_request_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE bill_payments (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 bill_type VARCHAR(40) NOT NULL,
 account_reference VARCHAR(80) NOT NULL,
 amount DECIMAL(18,2) NOT NULL,
 reference VARCHAR(30) NOT NULL UNIQUE,
 status VARCHAR(40) NOT NULL DEFAULT 'Paid (demo)',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_bill_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
