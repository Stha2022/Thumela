DROP DATABASE IF EXISTS thumela;
CREATE DATABASE thumela CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE thumela;

CREATE TABLE users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 first_name VARCHAR(60) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 preferred_language VARCHAR(10) NOT NULL DEFAULT 'en-ZA',
 voice_style VARCHAR(20) NOT NULL DEFAULT 'warm',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE wallets (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL UNIQUE,
 balance DECIMAL(18,2) NOT NULL DEFAULT 250.00,
 asset VARCHAR(12) NOT NULL DEFAULT 'USDT',
 network VARCHAR(40) NOT NULL DEFAULT 'Sepolia',
 CONSTRAINT fk_wallet_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE recipients (
 id INT AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NULL,
 name VARCHAR(100) NOT NULL,
 country VARCHAR(100) NOT NULL,
 address VARCHAR(120) NOT NULL,
 network VARCHAR(40) NOT NULL DEFAULT 'Sepolia',
 is_active TINYINT(1) NOT NULL DEFAULT 1,
 CONSTRAINT fk_recipient_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

